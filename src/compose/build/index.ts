// @fastly/hono-fastly-compute/compose/build: the build part of Fastly Hono
// Compose. It runs in Node, at build time and during development: it lists
// the plugins of the folder, and bundles them into one file of the app, which
// the app imports and gives to compose(). Never import this module in the code
// of the app: the Wasm bundle must not contain it.

import fs from 'node:fs';
import path from 'node:path';

// The folder of the plugins when the options do not give one, relative to the
// app directory.
export const DEFAULT_PLUGINS_DIR = './hono-compose';

// The file that the build writes into the app, relative to the app directory.
// The app imports `plugins` from it. The build also writes its types, in the
// same place with the extension .d.ts.
export const PLUGINS_MANIFEST = 'src/hono-compose.generated.js';

const THIS_PACKAGE = '@fastly/hono-fastly-compute';
const PLUGIN_FILE = /\.(?:js|mjs|ts|mts)$/;
// A file with this name (with any extension of PLUGIN_FILE) is not a plugin.
// The name is kept for a later configuration file of the folder.
const RESERVED_NAME = 'index';

export type PluginFile = {
  // The file name without the order prefix and the extension. It is the key in
  // the pluginOptions of compose().
  name: string,
  // The file name, in the folder.
  file: string,
};

// The plugins of the folder: the files directly in the folder with the
// extension .js, .mjs, .ts, or .mts, in file-name order. Files that start with
// '_' or '.', .d.ts files, and the files in subfolders (for example lib/) are
// not plugins. Throws for a file with the reserved name index, and if two
// plugins have the same name.
export function listPlugins(dir: string): PluginFile[] {
  if (!fs.existsSync(dir)) {
    return [];
  }
  const label = path.basename(dir);
  const files = fs.readdirSync(dir, { withFileTypes: true })
    .filter(entry => entry.isFile() && !entry.name.startsWith('_') && !entry.name.startsWith('.'))
    .map(entry => entry.name)
    .filter(file => PLUGIN_FILE.test(file) && !/\.d\.[cm]?ts$/.test(file))
    .sort();
  const plugins: PluginFile[] = [];
  const seen = new Map<string, string>();
  for (const file of files) {
    const base = file.replace(/\.[cm]?[jt]s$/, '');
    if (base === RESERVED_NAME) {
      throw new Error(
        `${label}/${file}: '${RESERVED_NAME}' is a reserved name in this folder. ` +
        `Rename the file, for example to 10-${file}.`,
      );
    }
    const name = base.replace(/^\d+-/, '');
    const other = seen.get(name);
    if (other != null) {
      throw new Error(`${label}: ${other} and ${file} have the same plugin name '${name}'.`);
    }
    seen.set(name, file);
    plugins.push({ name, file });
  }
  return plugins;
}

function readJson(file: string): any {
  return JSON.parse(fs.readFileSync(file, 'utf-8'));
}

// The packages that the app provides to the plugins: each package in the
// dependencies of the app's package.json, and this package, each also with
// its subpaths, and the fastly:* modules of the runtime. The bundle of the
// plugins leaves their imports, so that the app's copy is the only copy.
export function pluginsExternals(appDir: string): string[] {
  const packageJson = readJson(path.resolve(appDir, 'package.json'));
  const names = new Set([ ...Object.keys(packageJson.dependencies ?? {}), THIS_PACKAGE ]);
  return [ ...[ ...names ].sort().flatMap(name => [ name, `${name}/*` ]), 'fastly:*' ];
}

const GENERATED_HEADER = '// Generated by @fastly/hono-fastly-compute at each build. Do not edit.\n';

const MANIFEST_TYPES =
  GENERATED_HEADER +
  `import type { PluginEntry } from '${THIS_PACKAGE}/compose';\n\n` +
  'export declare const plugins: PluginEntry[];\n';

function entrySource(label: string, plugins: PluginFile[]) {
  const lines = plugins.map((plugin, i) => `import p${i} from ${JSON.stringify(`./${plugin.file}`)};`);
  const entries = plugins
    .map((plugin, i) => `  { name: ${JSON.stringify(plugin.name)}, file: ${JSON.stringify(`${label}/${plugin.file}`)}, plugin: p${i} },`)
    .join('\n');
  lines.push(`export const plugins = [\n${entries}\n];`);
  return lines.join('\n') + '\n';
}

// Writes a file, but only if its content changes, so that a watcher of the app
// (fastly compute serve --watch) does not see a change that is not one.
// Returns true if it wrote the file.
function writeIfChanged(file: string, content: string): boolean {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf-8') === content) {
    return false;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf-8');
  return true;
}

// Writes the manifest and its types. Returns true if it wrote the manifest.
function writeManifest(appDir: string, manifest: string, content: string): boolean {
  const file = path.resolve(appDir, manifest);
  writeIfChanged(file.replace(/\.js$/, '.d.ts'), MANIFEST_TYPES);
  return writeIfChanged(file, content);
}

export type WritePluginsStubOptions = {
  // The directory of the app.
  appDir: string,
  // The manifest, relative to appDir. Default: PLUGINS_MANIFEST.
  manifest?: string,
};

// Writes the manifest with no plugins, and its types. Then the app can import
// it before the first build, so that an editor does not show an error.
// Returns true if it wrote the manifest.
export function writePluginsStub(options: WritePluginsStubOptions): boolean {
  return writeManifest(options.appDir, options.manifest ?? PLUGINS_MANIFEST, GENERATED_HEADER + 'export const plugins = [];\n');
}

type ParsedVersion = { core: number[], prerelease: (string | number)[] };

function parseVersion(version: string): ParsedVersion | null {
  const match = /^v?(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?(?:\+.*)?$/.exec(version.trim());
  if (match == null) {
    return null;
  }
  return {
    core: [ Number(match[1]), Number(match[2]), Number(match[3]) ],
    prerelease: match[4] != null ? match[4].split('.').map(x => /^\d+$/.test(x) ? Number(x) : x) : [],
  };
}

// Semver order: -1 if a < b, 0 if the same, 1 if a > b. null if one of them
// is not a version.
function compareVersions(a: string, b: string): -1 | 0 | 1 | null {
  const va = parseVersion(a);
  const vb = parseVersion(b);
  if (va == null || vb == null) {
    return null;
  }
  for (let i = 0; i < 3; i++) {
    if (va.core[i] !== vb.core[i]) {
      return va.core[i]! < vb.core[i]! ? -1 : 1;
    }
  }
  // A version without a prerelease is after the same version with one.
  if (va.prerelease.length === 0 || vb.prerelease.length === 0) {
    return va.prerelease.length === vb.prerelease.length ? 0 : va.prerelease.length === 0 ? 1 : -1;
  }
  for (let i = 0; i < Math.max(va.prerelease.length, vb.prerelease.length); i++) {
    const x = va.prerelease[i];
    const y = vb.prerelease[i];
    if (x === undefined) {
      return -1;
    }
    if (y === undefined) {
      return 1;
    }
    if (x === y) {
      continue;
    }
    if (typeof x === 'number' && typeof y === 'number') {
      return x < y ? -1 : 1;
    }
    if (typeof x === 'number') {
      return -1;
    }
    if (typeof y === 'number') {
      return 1;
    }
    return x < y ? -1 : 1;
  }
  return 0;
}

// A small part of semver ranges: ^, ~, >=, an exact version, and *. Returns
// null for a range that this cannot read, so that no warning is given.
function satisfiesRange(version: string, range: string): boolean | null {
  const r = range.trim();
  if (r === '*' || r === '' || r === 'latest') {
    return true;
  }
  const match = /^(\^|~|>=)?\s*v?(\d+)(?:\.(\d+))?(?:\.(\d+))?$/.exec(r);
  if (match == null) {
    return null;
  }
  const [ , op, major, minor = '0', patch = '0' ] = match;
  const base = `${major}.${minor}.${patch}`;
  const cmp = compareVersions(version, base);
  if (cmp == null) {
    return null;
  }
  const [ vMajor, vMinor ] = version.split('.').map(Number);
  switch (op) {
  case '>=':
    return cmp >= 0;
  case '^':
    return cmp >= 0 && (Number(major) > 0 ? vMajor === Number(major) : vMajor === 0 && vMinor === Number(minor));
  case '~':
    return cmp >= 0 && vMajor === Number(major) && vMinor === Number(minor);
  default:
    // 4 is any 4.x.x, 4.13 is any 4.13.x, and 4.13.2 is only that version.
    if (match[3] == null) {
      return vMajor === Number(major);
    }
    if (match[4] == null) {
      return vMajor === Number(major) && vMinor === Number(minor);
    }
    return cmp === 0;
  }
}

export type CheckProvidedVersionsOptions = {
  // A sentence at the end of each warning, for example the command that
  // updates the folder's package.json.
  hint?: string,
};

// The warnings about the packages that the app provides: a range in the
// folder's package.json that does not include the version that the app has.
// The build uses the app's copy, so this is only a warning.
export function checkProvidedVersions(appDir: string, dir: string, options: CheckProvidedVersionsOptions = {}): string[] {
  const folderPackageJsonPath = path.resolve(dir, 'package.json');
  if (!fs.existsSync(folderPackageJsonPath)) {
    return [];
  }
  const folderPackageJson = readJson(folderPackageJsonPath);
  const ranges: Record<string, string> = {
    ...folderPackageJson.devDependencies,
    ...folderPackageJson.dependencies,
    ...folderPackageJson.peerDependencies,
  };
  const provided = new Set(pluginsExternals(appDir).filter(x => !x.endsWith('/*') && x !== 'fastly:*'));
  const label = path.basename(dir);
  const warnings: string[] = [];
  for (const [ name, range ] of Object.entries(ranges)) {
    if (!provided.has(name)) {
      continue;
    }
    const installed = path.resolve(appDir, 'node_modules', name, 'package.json');
    if (!fs.existsSync(installed)) {
      continue;
    }
    const version = readJson(installed).version;
    if (satisfiesRange(version, range) === false) {
      warnings.push(
        `${label}/package.json expects ${name} ${range}, but the app provides ${version}. ` +
        `The build uses the app's ${name}.` +
        (options.hint != null ? ` ${options.hint}` : ''),
      );
    }
  }
  return warnings;
}

// The esbuild module of the app (import * as esbuild from 'esbuild'). The
// app passes it, so that this package does not depend on esbuild.
export type Esbuild = { build: (options: any) => Promise<{ outputFiles?: { text: string }[] }> };

export type BundlePluginsOptions = {
  // The directory of the app: the directory of its package.json.
  appDir: string,
  esbuild: Esbuild,
  // The folder of the plugins, relative to appDir. Default: DEFAULT_PLUGINS_DIR.
  dir?: string,
  // The manifest, relative to appDir. Default: PLUGINS_MANIFEST.
  manifest?: string,
  // The options of each plugin, by name, that the app gives to compose(). The
  // build warns about a name that no plugin has.
  pluginOptions?: Record<string, unknown>,
  // The name of pluginOptions in that warning. Default: 'pluginOptions'.
  pluginOptionsSource?: string,
  // A sentence at the end of each warning about versions (see
  // checkProvidedVersions()).
  hint?: string,
};

// The folder of the plugins, as an absolute path.
export function pluginsDir(options: Pick<BundlePluginsOptions, 'appDir' | 'dir'>): string {
  return path.resolve(options.appDir, options.dir ?? DEFAULT_PLUGINS_DIR);
}

// Bundles the plugins of the folder into one file of the app (the manifest),
// which exports `plugins` for compose(). It also writes the types of the
// manifest. The packages that the app provides stay imports (see
// pluginsExternals()), so that the Wasm bundle has one copy of each. Without
// the folder, or without plugins, it writes the manifest with no plugins. It
// writes a file only if its content changes. Returns true if it wrote the
// manifest.
export async function bundlePlugins(options: BundlePluginsOptions): Promise<boolean> {
  const { appDir, esbuild } = options;
  const manifest = options.manifest ?? PLUGINS_MANIFEST;
  const dir = pluginsDir(options);
  if (!fs.existsSync(dir)) {
    return writePluginsStub({ appDir, manifest });
  }

  const label = path.basename(dir);
  const plugins = listPlugins(dir);
  const names = new Set(plugins.map(plugin => plugin.name));
  for (const name of Object.keys(options.pluginOptions ?? {})) {
    if (!names.has(name)) {
      console.warn(`⚠️ ${options.pluginOptionsSource ?? 'pluginOptions'}.${name}: there is no plugin '${name}' in ${label}/.`);
    }
  }
  for (const warning of checkProvidedVersions(appDir, dir, { hint: options.hint })) {
    console.warn(`⚠️ ${warning}`);
  }
  if (plugins.length === 0) {
    return writePluginsStub({ appDir, manifest });
  }

  const outfile = path.resolve(appDir, manifest);
  const result = await esbuild.build({
    stdin: { contents: entrySource(label, plugins), resolveDir: dir, sourcefile: `${label}.js`, loader: 'js' },
    bundle: true,
    format: 'esm',
    // As js-compute's own bundler, so that packages resolve the same way.
    conditions: [ 'fastly' ],
    external: pluginsExternals(appDir),
    outfile,
    banner: { js: GENERATED_HEADER.trimEnd() },
    logLevel: 'warning',
    write: false,
  });
  const text = result.outputFiles?.[0]?.text;
  if (text == null) {
    throw new Error(`${label}: esbuild gave no output.`);
  }
  return writeManifest(appDir, manifest, text);
}

export type PluginsWatcher = {
  close: () => void,
};

const WATCH_DELAY_MS = 100;

// Watches the folder of the plugins, and bundles them again after each change
// (see bundlePlugins()). fastly compute serve --watch watches only the app
// directory: a new manifest is the change that makes it build the app again.
// All files in the folder count, except node_modules/, so that a new plugin
// and a changed helper are found. Imports from outside the folder are not
// watched. While the folder does not exist, it checks each second if the
// folder was made. A failed bundle shows the error and keeps the manifest that
// the app has.
export async function watchPlugins(options: BundlePluginsOptions): Promise<PluginsWatcher> {
  const dir = pluginsDir(options);
  const manifest = options.manifest ?? PLUGINS_MANIFEST;

  let closed = false;
  let folderWatcher: fs.FSWatcher | undefined;
  let timer: NodeJS.Timeout | undefined;
  let running: Promise<void> | undefined;
  let again = false;

  const bundle = async () => {
    try {
      if (await bundlePlugins(options)) {
        console.log(`🔄 ${manifest} changed.`);
      }
    } catch (err) {
      console.error(`❌ Could not bundle the plugins: ${String(err instanceof Error ? err.message : err)}`);
    }
  };

  // One bundle at a time. A change during a bundle starts one more bundle.
  const run = () => {
    if (running != null) {
      again = true;
      return;
    }
    running = (async () => {
      do {
        again = false;
        await bundle();
        watchFolder();
      } while (again && !closed);
      running = undefined;
    })();
  };

  const schedule = () => {
    if (closed) {
      return;
    }
    clearTimeout(timer);
    timer = setTimeout(run, WATCH_DELAY_MS);
  };

  // Watches the folder if it exists. Stops the watch if the folder was removed.
  const watchFolder = () => {
    if (closed) {
      return;
    }
    const exists = fs.existsSync(dir);
    if (exists && folderWatcher == null) {
      folderWatcher = fs.watch(dir, { recursive: true }, (_event, file) => {
        if (file == null || !file.toString().split(/[\\/]/).includes('node_modules')) {
          schedule();
        }
      });
      // For example, the folder was removed.
      folderWatcher.on('error', () => {
        folderWatcher?.close();
        folderWatcher = undefined;
        schedule();
      });
    } else if (!exists && folderWatcher != null) {
      folderWatcher.close();
      folderWatcher = undefined;
    }
  };

  // While the folder does not exist, a check each second. The timer also keeps
  // the process of the watch script alive until close().
  const poll = setInterval(() => {
    if (folderWatcher == null && running == null && fs.existsSync(dir)) {
      schedule();
    }
  }, 1000);

  await bundle();
  watchFolder();

  return {
    close: () => {
      closed = true;
      clearTimeout(timer);
      clearInterval(poll);
      folderWatcher?.close();
    },
  };
}
